"""Recompile a Vita module's code to C++ (plan Phase 3, docs/decisions.md D6).

usage: python -I recomp/recompile.py <elf> <out dir> [--load-base HEX] [--bucket-bytes N] [--only ADDR,...]

--load-base: where Vita3K loads a relocatable module's code segment (libc 8031e000, libfios2
8036f000, libult 80454000 on 1.30); the code is generated for that address

Writes to <out dir> (under generated/, never committed):
  funcs.h          prototypes of every recompiled function
  bucket_NNN.cpp   the functions, about --bucket-bytes of guest code per file (default 64 KiB)
  table.cpp        sorted address -> function table, resume points, module name and code hash
                   (aot_abi.h)
  report.txt       coverage: recompiled / left to the fallback CPU, unsupported instructions
"""
import bisect, collections, glob, io, os, sys, time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from armrecomp.frontend import Module  # noqa: E402
from armrecomp.emit import FunctionEmitter, fname  # noqa: E402
from armrecomp import semantics  # noqa: E402

HEADER = '''// Generated by recomp/recompile.py from {elf}. Do not edit; never commit (docs/decisions.md D2).
#include "armrecomp.h"
#include "neon.h"
#include "funcs.h"

namespace armrecomp {{
'''


def translatable(f, mod):
    """every instruction of f has a translation (NEON and ARM mode included)"""
    if f.thumb and not f.uses_neon:
        return True  # Thumb integer/VFP code always translates (report.txt counts any exception)
    return all(semantics.translate(ins, f.thumb, mod.imports, f.start, f.end, f.jumptables, mod.patched).kind != 'unsupported'
               for ins in f.instructions)


class Output(io.StringIO):
    """A generated file, written only when its content changes, so that the build stays incremental."""

    def __init__(self, path):
        super().__init__()
        self.path = path

    def __exit__(self, *exc):
        text = self.getvalue()
        try:
            with open(self.path, encoding='utf-8') as fh:
                same = fh.read() == text
        except FileNotFoundError:
            same = False
        if not same:
            with open(self.path, 'w', encoding='utf-8') as fh:
                fh.write(text)
        return super().__exit__(*exc)


def main():
    args = sys.argv[1:]
    elf, out = args[0], args[1]
    bucket_bytes = 64 * 1024
    only = None
    if '--bucket-bytes' in args:
        bucket_bytes = int(args[args.index('--bucket-bytes') + 1])
    load_base = int(args[args.index('--load-base') + 1], 16) if '--load-base' in args else None
    if '--only' in args:
        only = {int(x, 16) for x in args[args.index('--only') + 1].split(',')}
    os.makedirs(out, exist_ok=True)
    t0 = time.time()
    mod = Module(elf, load_base=load_base)
    print(f'decoded in {time.time() - t0:.0f} s')

    reasons = collections.Counter()
    native = []
    for f in mod.functions:
        if f.kind != 'code':
            continue
        ok = translatable(f, mod)
        f.release()
        if not ok:
            reasons['untranslatable'] += 1
        elif only is not None and f.start not in only:
            reasons['not_selected'] += 1
        else:
            native.append(f)
    recompiled = {f.start for f in native}

    unsupported = collections.Counter()
    totals = collections.Counter()
    buckets, current, size = [], [], 0
    resumes = []  # (resume address | Thumb, function)
    for f in native:
        text, stats = FunctionEmitter(f, mod, recompiled).emit()
        f.release()
        resumes += [(a | (1 if f.thumb else 0), f) for a in stats.pop('resumes')]
        totals.update(stats)
        if stats['unsupported']:
            totals['functions_with_unsupported'] += 1
            for line in text.splitlines():
                if 'unsupported(ctx' in line and '//' in line:
                    unsupported[line.split('//', 1)[1].strip().split(' ')[0]] += 1
        current.append(text)
        size += f.end - f.start
        if size >= bucket_bytes:
            buckets.append(current)
            current, size = [], 0
    if current:
        buckets.append(current)

    for stale in glob.glob(os.path.join(out, 'bucket_*.cpp')):
        if int(os.path.basename(stale)[7:10]) >= len(buckets):
            os.remove(stale)
    for i, b in enumerate(buckets):
        with Output(os.path.join(out, f'bucket_{i:03d}.cpp')) as fh:
            fh.write(HEADER.format(elf=os.path.basename(elf)))
            fh.write('\n\n'.join(b))
            fh.write('\n\n} // namespace armrecomp\n')
    with Output(os.path.join(out, 'funcs.h')) as fh:
        fh.write('// Generated by recomp/recompile.py. Do not edit; never commit.\n#pragma once\n\nnamespace armrecomp {\n')
        fh.write('struct GuestContext;\n')
        for f in native:
            fh.write(f'void {fname(f.start)}(GuestContext *ctx);\n')
        fh.write('} // namespace armrecomp\n')
    # identity of the code the functions were generated from (aot_abi.h AotModule::code_hash)
    # words the loader rewrites (variable imports, relocations) are hashed as zero
    ranges = sorted((f.start, f.end) for f in native)
    starts = [r[0] for r in ranges]
    def in_native(a):
        i = bisect.bisect_right(starts, a) - 1
        return i >= 0 and a < ranges[i][1]
    patched = sorted(a for a in mod.patched_words if in_native(a))
    code = bytearray(mod.inv.code)
    base = mod.inv.text.vaddr + mod.delta  # runtime address of code[0]
    for a in patched:
        o = a - base
        code[o:o + 4] = bytes(4)
    code_hash = 0xcbf29ce484222325
    for f in native:
        o = f.start - base
        for b in code[o:o + (f.end - f.start)]:
            code_hash = ((code_hash ^ b) * 0x100000001b3) & 0xffffffffffffffff
    with Output(os.path.join(out, 'table.cpp')) as fh:
        fh.write(HEADER.format(elf=os.path.basename(elf)))
        fh.write('extern const AotFunction g_functions[] = {\n')
        for f in native:
            fh.write(f'    {{0x{f.start | (1 if f.thumb else 0):08x}u, {f.end - f.start}u, {fname(f.start)}}},\n')
        fh.write('};\n')
        fh.write(f'extern const uint32_t g_function_count = {len(native)};\n')
        fh.write(f'extern const uint64_t g_code_hash = 0x{code_hash:016x}ull;\n')
        fh.write(f'extern const char g_module_name[] = "{os.path.basename(elf)}";\n')
        fh.write('extern const uint32_t g_patched[] = {' + ', '.join(f'0x{a:08x}u' for a in patched or [0]) + '};\n')
        fh.write(f'extern const uint32_t g_patched_count = {len(patched)};\n')
        fh.write('extern const AotResume g_resumes[] = {\n')
        for a, f in sorted(resumes, key=lambda r: r[0]):
            fh.write(f'    {{0x{a:08x}u, 0x{f.start | (1 if f.thumb else 0):08x}u, {fname(f.start)}}},\n')
        if not resumes:
            fh.write('    {0, 0, nullptr},\n')
        fh.write('};\n')
        fh.write(f'extern const uint32_t g_resume_count = {len(resumes)};\n')
        fh.write('} // namespace armrecomp\n')

    lines = [
        f'{os.path.basename(elf)}: {len(native)} functions recompiled, left to the fallback CPU: {dict(reasons)}',
        f'instructions: {totals["insns"]}, unsupported: {totals["unsupported"]} in {totals["functions_with_unsupported"]} functions',
        f'flag writes dropped as dead: {totals["flags_dropped"]}',
        f'resume points (call return sites): {len(resumes)}',
        f'buckets: {len(buckets)} (about {bucket_bytes} bytes of guest code each)',
        f'code hash: {code_hash:016x}',
        'unsupported by mnemonic: ' + ', '.join(f'{m} {n}' for m, n in unsupported.most_common(40)),
        f'time: {time.time() - t0:.0f} s',
    ]
    open(os.path.join(out, 'report.txt'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
