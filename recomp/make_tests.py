"""Generate the dynarmic comparison tests (plan Phase 3). recomp/tests/harness.cpp runs each on
random inputs, natively and on dynarmic.

  tests.cpp      per instruction: for each instruction form used by the module's recompiled code,
                 up to N distinct encodings become single-instruction test functions
  functions.cpp  per function: up to M leaf functions with control flow (branches, IT blocks,
                 jump tables, loops), emitted exactly as recompile.py emits them and run to their
                 return

usage: python -I recomp/make_tests.py <elf> <out dir> [--per-form N] [--functions M]
"""
import collections, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from armrecomp.frontend import Module  # noqa: E402
from armrecomp import semantics  # noqa: E402
from armrecomp.emit import FunctionEmitter, fname  # noqa: E402
from forms import form  # noqa: E402

COND_CODE = {'eq': 0, 'ne': 1, 'cs': 2, 'hs': 2, 'cc': 3, 'lo': 3, 'mi': 4, 'pl': 5, 'vs': 6, 'vc': 7,
             'hi': 8, 'ls': 9, 'ge': 10, 'lt': 11, 'gt': 12, 'le': 13}
SKIP = ('ldrex', 'strex', 'clrex', 'mrc', 'mcr')  # exclusives: single-thread semantics in v0; mrc/mcr: TLS (no CP15 in the harness)
CONTROL = ('branch', 'cond_branch', 'jumptable')
MAX_FUNCTION_BYTES = 4096


def leaf_functions(mod, count):
    """up to `count` leaf functions with control flow, evenly spread over the module"""
    found = []
    for f in mod.functions:
        if f.kind != 'code' or f.end - f.start > MAX_FUNCTION_BYTES:
            continue
        skip = any(ins.mnemonic.startswith(SKIP) for ins in f.instructions)
        kinds = set() if skip else {semantics.translate(ins, f.thumb, mod.imports, f.start, f.end, f.jumptables).kind
                                    for ins in f.instructions}
        f.release()
        if skip:
            continue
        if 'return' not in kinds or not kinds & set(CONTROL):
            continue
        if kinds & {'call', 'call_import', 'call_indirect', 'jump_indirect', 'trap', 'unsupported'}:
            continue
        found.append(f)
    step = max(1, len(found) / count) if count else 1
    picked = [found[int(i * step)] for i in range(min(count, len(found)))]
    # ARM-mode leaves are few: test them all
    picked += [f for f in found if not f.thumb and f not in picked]
    return picked, len(found)


def function_tests(mod, out, count):
    funcs, total = leaf_functions(mod, count)
    lines = ['// Generated by recomp/make_tests.py. Never commit (derived from the game).',
             '#include "armrecomp.h"', '#include "neon.h"', '#include "tests.h"', '', 'namespace armrecomp {', '']
    ninsns = {}
    for f in funcs:
        text, _ = FunctionEmitter(f, mod, {f.start}).emit()
        ninsns[f.start] = len(f.instructions)
        f.release()
        lines.append('static ' + text)
        code = mod.code_bytes(f.start, f.end - f.start)
        lines.append(f'static const uint8_t code_{f.start:08x}[] = {{')
        for k in range(0, len(code), 24):
            lines.append('    ' + ', '.join(f'0x{b:02x}' for b in code[k:k + 24]) + ',')
        lines.append('};')
        lines.append('')
    lines.append('extern const FunctionTest g_function_tests[] = {')
    for f in funcs:
        lines.append(f'    {{0x{f.start:08x}u, {f.end - f.start}u, code_{f.start:08x}, {fname(f.start)}, '
                     f'{ninsns[f.start]}u, {1 if f.thumb else 0}}},')
    if not funcs:
        lines.append('    {0, 0, nullptr, nullptr, 0, 1},')
    lines.append('};')
    lines.append(f'extern const uint32_t g_function_test_count = {len(funcs)};')
    lines.append('} // namespace armrecomp')
    open(os.path.join(out, 'functions.cpp'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{len(funcs)} function tests (of {total} leaf functions with control flow)')


def main():
    elf, out = sys.argv[1], sys.argv[2]
    per_form = int(sys.argv[sys.argv.index('--per-form') + 1]) if '--per-form' in sys.argv else 20
    functions = int(sys.argv[sys.argv.index('--functions') + 1]) if '--functions' in sys.argv else 300
    os.makedirs(out, exist_ok=True)
    mod = Module(elf)
    chosen = collections.defaultdict(dict)  # form -> {(bytes, it_cond): (instruction, translation, thumb)}
    for f in mod.functions:
        if f.kind != 'code':
            continue
        for ins in f.instructions:
            if ins.mnemonic.startswith(SKIP):
                continue
            key = (bytes(ins.cs.bytes), ins.it_cond)
            slot = chosen[form(ins) if f.thumb else 'arm:' + form(ins)]
            if key in slot or len(slot) >= per_form:
                continue
            t = semantics.translate(ins, f.thumb, mod.imports, f.start, f.end, f.jumptables)
            if t.kind != 'seq':
                continue
            slot[key] = (ins, t, f.thumb)
        f.release()

    tests = [(fm, ins, t, thumb) for fm, slot in sorted(chosen.items()) for ins, t, thumb in slot.values()]
    lines = ['// Generated by recomp/make_tests.py. Never commit (derived from the game).',
             '#include "armrecomp.h"', '#include "neon.h"', '#include "tests.h"', '', 'namespace armrecomp {', '']
    for n, (fm, ins, t, thumb) in enumerate(tests):
        lines.append(f'// {ins.address:08x}: {ins.cs.mnemonic} {ins.cs.op_str} [{fm}]'
                     + (f' (IT {ins.it_cond})' if ins.it_cond else ''))
        lines.append(f'static void t_{n}(GuestContext *ctx) {{')
        body = [s[2] if isinstance(s, tuple) else s for s in t.stmts]
        if ins.it_cond:
            lines.append(f'    if ({semantics.COND_EXPR[ins.it_cond]}) {{')
            lines += ['        ' + b for b in body]
            lines.append('    }')
        else:
            lines += ['    ' + b for b in body]
        lines.append('}')
    lines.append('')
    lines.append('extern const TestCase g_tests[] = {')
    for n, (fm, ins, t, thumb) in enumerate(tests):
        b = bytes(ins.cs.bytes) + b'\0' * (4 - ins.size)
        text = f'{ins.cs.mnemonic} {ins.cs.op_str}'.replace('"', "'")
        # an IT prefix only for Thumb; an ARM instruction carries its condition
        cond = COND_CODE[ins.it_cond] if ins.it_cond and thumb else -1
        lines.append(f'    {{0x{ins.address:08x}u, {{0x{b[0]:02x}, 0x{b[1]:02x}, 0x{b[2]:02x}, 0x{b[3]:02x}}}, '
                     f'{ins.size}, {cond}, t_{n}, "{text}", "{fm}", {1 if thumb else 0}}},')
    lines.append('};')
    lines.append(f'extern const uint32_t g_test_count = {len(tests)};')
    lines.append('} // namespace armrecomp')
    open(os.path.join(out, 'tests.cpp'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{len(tests)} tests from {len(chosen)} forms')
    function_tests(mod, out, functions)


if __name__ == '__main__':
    main()
